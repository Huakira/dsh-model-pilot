function pick(): Record<string, string> {
  const lang = (typeof navigator !== "undefined" && navigator.language) || "en";
  return lang.toLowerCase().startsWith("zh") ? zh : en;
}

const dict = pick();
export function t(key: string): string {
  return dict[key] ?? en[key] ?? key;
}